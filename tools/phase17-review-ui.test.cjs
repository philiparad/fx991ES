'use strict';
const assert=require('node:assert/strict');
const R=require('../src/phase17-review-ui.js');
const plan=[{id:'F16-01',checkpoints:[1,3],keys:['FRAC','1','RIGHT']}];
const corpus={schema:'fx991-device-evidence-v1',records:[{id:'test-01',scenarioId:'F16-01',kind:'physical',device:'SYNTHETIC FIXTURE',observed:{result:'test'},checkpoints:[{step:1,observed:{expression:'fixture'}}]}]};
const items=R.readEvidence(JSON.stringify(corpus),plan);
assert.equal(items.length,1);assert.deepEqual(items[0].missing,[3]);
assert.deepEqual(R.reviewDocument(items,[]),{schema:R.SCHEMA,reviews:[]});
const input={scenarioId:'F16-01',observationId:'test-01',reviewer:'Second reviewer',reviewedAt:'2026-11-06',disposition:'inconclusive',physicalKeyMappingConfirmed:false,checkpointsVerified:false,notes:'Synthetic only; no photos'};
const result=R.reviewDocument(items,[input]);
assert.equal(result.reviews.length,1);assert.equal(result.reviews[0].disposition,'inconclusive');
assert.equal(result.reviews[0].checkpointsVerified,false);
assert.throws(()=>R.reviewDocument(items,[{...input,disposition:''}]),/disposition/);
assert.throws(()=>R.reviewDocument(items,[{...input,physicalKeyMappingConfirmed:undefined}]),/mapping/);
assert.throws(()=>R.reviewDocument(items,[{...input,notes:''}]),/notes/);
assert.throws(()=>R.reviewDocument(items,[{...input,observationId:'wrong'}]),/Unmatched/);
assert.throws(()=>R.readEvidence(JSON.stringify({...corpus,records:[...corpus.records,...corpus.records]}),plan),/Duplicate/);
assert.throws(()=>R.readEvidence(JSON.stringify({...corpus,records:[{...corpus.records[0],checkpoints:[{step:3,observed:{}}]}]}),plan),/Empty observed/);
console.log('Phase 17 independent review UI tests passed (synthetic metadata only)');
